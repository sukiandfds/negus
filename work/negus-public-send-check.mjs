import {chromium} from '/Users/hans/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright-core/index.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {config} from '../scripts/negus-service-common.mjs';
const cfg=await config();
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const result={startedAt:new Date().toISOString(),origin:'https://codex.negus.us.ci',requests:[],failures:[]};
let page;
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 await context.addCookies([{name:'codex_demo_token',value:cfg.token,url:result.origin}]);
 page=await context.newPage();
 page.on('requestfailed',r=>{const path=new URL(r.url()).pathname;if(path.startsWith('/api/')||path==='/events')result.failures.push({path,error:r.failure()});});
 page.on('response',r=>{const path=new URL(r.url()).pathname;if(r.request().method()==='POST'){result.requests.push({path,status:r.status()});console.log('POST',path,r.status());}});
 await page.goto(result.origin+'/?view=conversation',{waitUntil:'domcontentloaded',timeout:45000});
 await page.getByRole('button',{name:'添加',exact:true}).click();
 await page.getByRole('menuitem',{name:'新建对话',exact:true}).click();
 const expected='NEGUS-PUBLIC-REPLY-'+Date.now();result.expected=expected;
 result.prompt='这是一条真实公网收发验收消息。请只回复下面这一行，不调用工具，不修改任何文件：\n'+expected;
 const input=page.getByPlaceholder('给 Codex 发送指令',{exact:true});
 await input.fill(result.prompt);
 const created=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/session'&&r.request().method()==='POST',{timeout:45000});
 await page.getByRole('button',{name:'发送',exact:true}).click();console.log('SENT');
 const response=await created; assert.equal(response.status(),201);
 const session=await response.json();result.threadId=session.threadId;assert.ok(result.threadId);console.log('CREATED',result.threadId);
 const assistant=page.locator('article[class*="assistant"]').filter({hasText:expected});
 await assistant.waitFor({state:'visible',timeout:120000});
 result.visibleReply=await assistant.innerText();console.log('RECEIVED',result.visibleReply);
 await page.screenshot({path:'work/negus-public-send-received.png',fullPage:true});
 await page.reload({waitUntil:'domcontentloaded',timeout:45000});
 await page.locator('article[class*="assistant"]').filter({hasText:expected}).waitFor({state:'visible',timeout:30000});
 const saved=await page.evaluate(async id=>{const r=await fetch('/api/session?threadId='+encodeURIComponent(id)+'&limit=60');return {status:r.status,body:await r.json()};},result.threadId);
 assert.equal(saved.status,200);
 const reply=saved.body.messages.find(m=>m.role==='assistant'&&m.text?.includes(expected));assert.ok(reply,'reply must be stored as an assistant message');
 result.persistedReply={id:reply.id,role:reply.role,text:reply.text};
 result.url=page.url();result.passed=true;result.finishedAt=new Date().toISOString();
 await page.screenshot({path:'work/negus-public-send-reloaded.png',fullPage:true});
 console.log('PASS',JSON.stringify({threadId:result.threadId,reply:reply.text,url:result.url}));
} catch(e){result.error=e.message;console.log('FAIL',e.message);if(page){console.log('BODY',(await page.locator('body').innerText().catch(()=>'' )).slice(-3500));await page.screenshot({path:'work/negus-public-send-failed.png',fullPage:true}).catch(()=>{});}process.exitCode=1;
} finally {await fs.writeFile('work/negus-public-send-result.json',JSON.stringify(result,null,2));await browser.close();}
