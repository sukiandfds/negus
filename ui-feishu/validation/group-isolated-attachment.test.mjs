import assert from 'node:assert/strict';
import { createMediaService } from '../../windows/server/media-service.mjs';
import { inputFromAttachments } from '../../windows/server/app-server-conversation-store.mjs';
const { NEGUS_TEST_ORIGIN: origin, NEGUS_TEST_ROOM: roomId, NEGUS_TEST_TOKEN: token, NEGUS_TEST_UPLOAD_ROOT: uploadRoot } = process.env;
if (!origin || !roomId || !token || !uploadRoot) throw Error('缺少隔离测试服务配置');
const response = await fetch(`${origin}/api/group/snapshot?roomId=${encodeURIComponent(roomId)}&token=${encodeURIComponent(token)}`);
assert.equal(response.ok, true);
const snapshot = await response.json();
const file = snapshot.messages.find(message => message.text === '隔离上传测试')?.attachments?.[0];
assert.ok(file);
const media = createMediaService({ uploadRoot });
await media.restoreUploads();
const resolved = media.resolveMany([file.id]);
assert.equal(resolved.length, 1);
const input = await inputFromAttachments('后台任务输入', resolved);
assert.equal(input.length, 1);
assert.ok(input[0].text.includes(`## isolation.txt: ${resolved[0].path}`));
assert.match(input[0].text, /## My request for Codex:\n\n后台任务输入$/u);
assert.doesNotMatch(input[0].text, /隔离附件内容/u);
